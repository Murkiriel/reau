def fatia(items, index, total):
    """The [index]-th (1-based) of [total] slices of [items]: every other one from the index-th, so each slice mixes the files."""
    return [m for n, m in enumerate(items) if n % total == index - 1]


def parse(argv):
    """(slice or None, only list, filters) from the command line."""
    part, only_list, filters, args = None, False, [], list(argv)
    while args:
        a = args.pop(0)
        if a == "--lista":
            only_list = True
        elif a == "--fatia":
            index, total = (int(x) for x in args.pop(0).split("/"))
            if not 1 <= index <= total:
                raise SystemExit(f"--fatia {index}/{total}: the index goes from 1 to {total}")
            part = (index, total)
        else:
            filters.append(a)
    return part, only_list, filters


def main(argv):
    part, only_list, filters = parse(argv)
    back = mutate.recover()
    if back:
        print(f"{back} arquivo(s) deixado(s) mutado(s) por uma execução interrompida foram restaurados", flush=True)
    wanted = [m for m in MUTATIONS if not filters or any(a in m[0] for a in filters)]
    if part:
        wanted = fatia(wanted, *part)
    if only_list:
        print(f"{len(wanted)} mutações")
        for m in wanted:
            print(" ", m[0])
        return 0
    caught = 0
    for name, rel, old, new, classes in wanted:
        caught += mutate.run([(name, rel, old, new)], [sys.executable, str(HERE / "run_unit.py"), *classes]) or 0
    print(f"\nTOTAL: {caught} de {len(wanted)} mutações pegas", flush=True)
    return 0 if caught == len(wanted) else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
